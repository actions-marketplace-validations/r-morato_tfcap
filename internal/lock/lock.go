// Package lock implements tfcap.lock.json: a module lock file that records,
// for every third-party module, the content hash and the capability set
// that was reviewed. Terraform's own .terraform.lock.hcl only covers
// providers; modules have no integrity record at all. This fills that gap.
package lock

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"

	"github.com/r-morato/tfcap/internal/model"
	"github.com/r-morato/tfcap/internal/rules"
)

const Schema = "tfcap/lock/v1"

// File is the on-disk lock format.
type File struct {
	Schema  string  `json:"schema"`
	Comment string  `json:"_comment,omitempty"`
	Modules []Entry `json:"modules"`
	// ProvidersLocked is set by tfcap >= 0.3, which also records the
	// provider checksums from .terraform.lock.hcl. Older lock files skip
	// provider checks until they are re-locked.
	ProvidersLocked bool            `json:"providers_locked,omitempty"`
	Providers       []ProviderEntry `json:"providers,omitempty"`
}

// ProviderEntry locks one provider from .terraform.lock.hcl.
type ProviderEntry struct {
	Address string   `json:"address"`
	Version string   `json:"version"`
	Hashes  []string `json:"hashes"`
}

// Entry locks one module.
type Entry struct {
	Key          string    `json:"key"`
	Source       string    `json:"source"`
	Version      string    `json:"version,omitempty"`
	Hash         string    `json:"hash"`
	Commit       string    `json:"commit,omitempty"` // git commit the version resolved to
	Capabilities []LockCap `json:"capabilities"`
}

// LockCap is a reviewed capability.
type LockCap struct {
	Fingerprint string `json:"fp"`
	RuleID      string `json:"rule"`
	Address     string `json:"address,omitempty"`
	Detail      string `json:"detail,omitempty"`
}

// Build creates a lock from a scan report. Only third-party modules are
// locked; your own code is reviewed through normal code review.
func Build(rep *model.Report) *File {
	f := &File{Schema: Schema, Comment: "Generated by tfcap. Commit this file. Re-run `tfcap lock` after reviewing module upgrades.", Modules: []Entry{}}
	caps := map[string][]model.Capability{}
	for _, c := range rep.Capabilities {
		caps[c.Module] = append(caps[c.Module], c)
	}
	for _, m := range rep.Modules {
		if !m.ThirdParty {
			continue
		}
		e := Entry{Key: m.Key, Source: m.Source, Version: m.Version, Hash: m.Hash, Commit: m.Commit, Capabilities: []LockCap{}}
		seen := map[string]bool{}
		for _, c := range caps[m.Key] {
			fp := c.Fingerprint()
			if seen[fp] {
				continue
			}
			seen[fp] = true
			e.Capabilities = append(e.Capabilities, LockCap{Fingerprint: fp, RuleID: c.RuleID, Address: c.Address, Detail: c.Detail})
		}
		sort.Slice(e.Capabilities, func(i, j int) bool {
			if e.Capabilities[i].RuleID != e.Capabilities[j].RuleID {
				return e.Capabilities[i].RuleID < e.Capabilities[j].RuleID
			}
			return e.Capabilities[i].Fingerprint < e.Capabilities[j].Fingerprint
		})
		f.Modules = append(f.Modules, e)
	}
	sort.Slice(f.Modules, func(i, j int) bool { return f.Modules[i].Key < f.Modules[j].Key })
	f.ProvidersLocked = true
	for _, p := range rep.ProviderLocks {
		f.Providers = append(f.Providers, ProviderEntry{Address: p.Address, Version: p.Version, Hashes: append([]string(nil), p.Hashes...)})
	}
	return f
}

// Read loads a lock file.
func Read(path string) (*File, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var f File
	if err := json.Unmarshal(b, &f); err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}
	if f.Schema != Schema {
		return nil, fmt.Errorf("%s: unsupported schema %q (want %q)", path, f.Schema, Schema)
	}
	return &f, nil
}

// Write saves a lock file with stable formatting.
func (f *File) Write(path string) error {
	b, err := json.MarshalIndent(f, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(b, '\n'), 0o644)
}

// Status of a module relative to the lock.
const (
	StatusOK       = "ok"
	StatusMutated  = "mutated"  // same source+version, different content
	StatusUpgraded = "upgraded" // source or version changed
	StatusNew      = "new"      // not in lock
	StatusRemoved  = "removed"  // in lock, no longer used
)

// ProviderStatus is the verification outcome for one provider.
type ProviderStatus struct {
	Address        string `json:"address"`
	Status         string `json:"status"` // ok, new, upgraded, mutated, removed
	LockedVersion  string `json:"locked_version,omitempty"`
	CurrentVersion string `json:"current_version,omitempty"`
}

// ModuleStatus is the verification outcome for one module.
type ModuleStatus struct {
	Key          string `json:"key"`
	Status       string `json:"status"`
	Source       string `json:"source,omitempty"`
	LockedSource string `json:"locked_source,omitempty"`
	LockedVer    string `json:"locked_version,omitempty"`
	CurrentVer   string `json:"current_version,omitempty"`
	LockedHash   string `json:"locked_hash,omitempty"`
	CurrentHash  string `json:"current_hash,omitempty"`
}

// Result of verifying a report against a lock.
type Result struct {
	Schema    string           `json:"schema"`
	Modules   []ModuleStatus   `json:"modules"`
	Providers []ProviderStatus `json:"providers,omitempty"`
	// Findings are capabilities that were not reviewed: mutation alerts plus
	// every capability that is new relative to the lock.
	Findings []model.Capability `json:"findings"`
	// Accepted are findings removed by tfcap.hcl exceptions.
	Accepted []model.Accepted `json:"accepted,omitempty"`
}

// Verify compares a fresh scan against the lock.
func Verify(f *File, rep *model.Report) *Result {
	res := &Result{Schema: "tfcap/verify/v1", Modules: []ModuleStatus{}, Findings: []model.Capability{}}
	locked := map[string]Entry{}
	for _, e := range f.Modules {
		locked[e.Key] = e
	}
	current := map[string]bool{}
	byModule := map[string][]model.Capability{}
	for _, c := range rep.Capabilities {
		byModule[c.Module] = append(byModule[c.Module], c)
	}
	for _, m := range rep.Modules {
		if !m.ThirdParty {
			continue
		}
		current[m.Key] = true
		e, ok := locked[m.Key]
		st := ModuleStatus{Key: m.Key, Source: m.Source, CurrentVer: m.Version, CurrentHash: m.Hash}
		known := map[string]bool{}
		switch {
		case !ok:
			st.Status = StatusNew
		case e.Source == m.Source && e.Version == m.Version && e.Hash != m.Hash:
			st.Status = StatusMutated
			st.LockedVer, st.LockedHash = e.Version, e.Hash
			r := rules.Get(rules.SrcContentChanged)
			res.Findings = append(res.Findings, model.Capability{
				RuleID: r.ID, Severity: r.Severity, Phase: r.Phase, Module: m.Key, Address: "module." + lastSegment(m.Key),
				Message: mutatedMessage(e, m),
				Detail:  "hash:" + m.Hash,
			})
			for _, c := range e.Capabilities {
				known[c.Fingerprint] = true
			}
		case e.Source != m.Source || e.Version != m.Version:
			st.Status = StatusUpgraded
			st.LockedVer, st.LockedHash, st.LockedSource = e.Version, e.Hash, e.Source
			for _, c := range e.Capabilities {
				known[c.Fingerprint] = true
			}
		default:
			st.Status = StatusOK
			st.LockedVer, st.LockedHash = e.Version, e.Hash
			for _, c := range e.Capabilities {
				known[c.Fingerprint] = true
			}
		}
		res.Modules = append(res.Modules, st)
		for _, c := range byModule[m.Key] {
			if !known[c.Fingerprint()] {
				res.Findings = append(res.Findings, c)
			}
		}
	}
	for _, e := range f.Modules {
		if !current[e.Key] {
			res.Modules = append(res.Modules, ModuleStatus{Key: e.Key, Status: StatusRemoved, Source: e.Source, LockedVer: e.Version, LockedHash: e.Hash})
		}
	}
	sort.Slice(res.Modules, func(i, j int) bool { return res.Modules[i].Key < res.Modules[j].Key })
	if f.ProvidersLocked {
		verifyProviders(f, rep, res)
	}
	sort.SliceStable(res.Findings, func(i, j int) bool {
		if res.Findings[i].Severity != res.Findings[j].Severity {
			return res.Findings[i].Severity > res.Findings[j].Severity
		}
		return res.Findings[i].Module < res.Findings[j].Module
	})
	return res
}

func lastSegment(k string) string {
	for i := len(k) - 1; i >= 0; i-- {
		if k[i] == '.' {
			return k[i+1:]
		}
	}
	return k
}

func withVersion(src, v string) string {
	if v == "" {
		return src
	}
	return src + "@" + v
}

func short(h string) string {
	const n = 18
	if len(h) > n {
		return h[:n] + "…"
	}
	return h
}

// Change describes how one module's lock entry changes.
type Change struct {
	Key     string `json:"key"`
	Kind    string `json:"kind"` // added, updated, removed, unchanged
	From    string `json:"from,omitempty"`
	To      string `json:"to,omitempty"`
	NewCaps int    `json:"new_capabilities,omitempty"`
}

// Merge builds the lock to write. With no `only` keys the fresh lock is
// used as-is. With `only`, the old lock is kept and just those modules are
// replaced (or added) from the fresh scan. It returns an error for a key
// that is not a third-party module in the fresh scan.
func Merge(old, fresh *File, only []string) (*File, error) {
	if len(only) == 0 || old == nil {
		if len(only) > 0 {
			for _, k := range only {
				if findEntry(fresh, k) == nil {
					return nil, fmt.Errorf("module %q is not a third-party module in this configuration", k)
				}
			}
		}
		return fresh, nil
	}
	out := &File{Schema: Schema, Comment: fresh.Comment, Modules: append([]Entry(nil), old.Modules...),
		ProvidersLocked: old.ProvidersLocked, Providers: old.Providers}
	for _, k := range only {
		e := findEntry(fresh, k)
		if e == nil {
			return nil, fmt.Errorf("module %q is not a third-party module in this configuration", k)
		}
		replaced := false
		for i := range out.Modules {
			if out.Modules[i].Key == k {
				out.Modules[i] = *e
				replaced = true
			}
		}
		if !replaced {
			out.Modules = append(out.Modules, *e)
		}
	}
	sort.Slice(out.Modules, func(i, j int) bool { return out.Modules[i].Key < out.Modules[j].Key })
	return out, nil
}

func findEntry(f *File, key string) *Entry {
	if f == nil {
		return nil
	}
	for i := range f.Modules {
		if f.Modules[i].Key == key {
			return &f.Modules[i]
		}
	}
	return nil
}

// Diff summarises how next differs from prev (prev may be nil).
func Diff(prev, next *File) []Change {
	var out []Change
	for _, n := range next.Modules {
		p := findEntry(prev, n.Key)
		switch {
		case p == nil:
			out = append(out, Change{Key: n.Key, Kind: "added", To: label(n), NewCaps: len(n.Capabilities)})
		case p.Hash == n.Hash && p.Source == n.Source && p.Version == n.Version:
			out = append(out, Change{Key: n.Key, Kind: "unchanged"})
		default:
			known := map[string]bool{}
			for _, c := range p.Capabilities {
				known[c.Fingerprint] = true
			}
			added := 0
			for _, c := range n.Capabilities {
				if !known[c.Fingerprint] {
					added++
				}
			}
			out = append(out, Change{Key: n.Key, Kind: "updated", From: label(*p), To: label(n), NewCaps: added})
		}
	}
	if prev != nil {
		for _, p := range prev.Modules {
			if findEntry(next, p.Key) == nil {
				out = append(out, Change{Key: p.Key, Kind: "removed", From: label(p)})
			}
		}
	}
	sort.SliceStable(out, func(i, j int) bool { return out[i].Key < out[j].Key })
	return out
}

func label(e Entry) string { return withVersion(e.Source, e.Version) }

var (
	hashRe   = regexp.MustCompile(`^tfcap1:[0-9a-f]{64}$`)
	commitRe = regexp.MustCompile(`^([0-9a-f]{40}|[0-9a-f]{64})$`)

	providerAddrRe = regexp.MustCompile(`^[a-z0-9.:-]+/[a-z0-9_-]+/[a-z0-9_-]+$`)
	providerHashRe = regexp.MustCompile(`^(h1:[A-Za-z0-9+/]+=*|zh:[0-9a-f]{64})$`)
	ruleRe         = regexp.MustCompile(`^TFCAP-[A-Z]+-[0-9]{3}$`)
	fpRe           = regexp.MustCompile(`^[0-9a-f]{16}$`)
)

// Validate strictly checks a lock file produced elsewhere (for example by a
// CI job that ran untrusted code) before it is trusted: known fields only,
// well-formed hashes, rule IDs and fingerprints, and a sane size.
func Validate(path string) error {
	st, err := os.Stat(path)
	if err != nil {
		return err
	}
	if st.Size() > 5<<20 {
		return fmt.Errorf("%s: lock file is unexpectedly large (%d bytes)", path, st.Size())
	}
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.DisallowUnknownFields()
	var f File
	if err := dec.Decode(&f); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	if dec.More() {
		return fmt.Errorf("%s: trailing data after the lock object", path)
	}
	if f.Schema != Schema {
		return fmt.Errorf("%s: unsupported schema %q", path, f.Schema)
	}
	for _, p := range f.Providers {
		if !providerAddrRe.MatchString(p.Address) || p.Version == "" || len(p.Version) > 64 {
			return fmt.Errorf("%s: malformed provider entry %q", path, p.Address)
		}
		for _, h := range p.Hashes {
			if !providerHashRe.MatchString(h) {
				return fmt.Errorf("%s: provider %q has a malformed hash", path, p.Address)
			}
		}
	}
	seen := map[string]bool{}
	for _, m := range f.Modules {
		switch {
		case m.Key == "" || seen[m.Key]:
			return fmt.Errorf("%s: empty or duplicate module key %q", path, m.Key)
		case m.Source == "":
			return fmt.Errorf("%s: module %q has no source", path, m.Key)
		case !hashRe.MatchString(m.Hash):
			return fmt.Errorf("%s: module %q has a malformed hash", path, m.Key)
		case m.Commit != "" && !commitRe.MatchString(m.Commit):
			return fmt.Errorf("%s: module %q has a malformed commit", path, m.Key)
		}
		seen[m.Key] = true
		for _, c := range m.Capabilities {
			if !ruleRe.MatchString(c.RuleID) || !fpRe.MatchString(c.Fingerprint) {
				return fmt.Errorf("%s: module %q has a malformed capability entry", path, m.Key)
			}
		}
	}
	return nil
}

func mutatedMessage(e Entry, m model.Module) string {
	msg := fmt.Sprintf("%s content changed since it was locked (%s → %s).", withVersion(m.Source, m.Version), short(e.Hash), short(m.Hash))
	if e.Commit != "" && m.Commit != "" && e.Commit != m.Commit {
		return msg + fmt.Sprintf(" The same version now resolves to commit %s (locked: %s): the tag was moved.", m.Commit[:12], e.Commit[:12])
	}
	return msg + " The tag or registry release was re-pointed."
}

func verifyProviders(f *File, rep *model.Report, res *Result) {
	locked := map[string]ProviderEntry{}
	for _, p := range f.Providers {
		locked[p.Address] = p
	}
	current := map[string]bool{}
	add := func(id string, p model.ProviderLock, msg, detail string) {
		r := rules.Get(id)
		res.Findings = append(res.Findings, model.Capability{RuleID: r.ID, Severity: r.Severity, Phase: r.Phase,
			Address: "provider." + p.Address, File: ".terraform.lock.hcl", Line: p.Line, Message: msg, Detail: detail})
	}
	for _, p := range rep.ProviderLocks {
		current[p.Address] = true
		e, ok := locked[p.Address]
		st := ProviderStatus{Address: p.Address, CurrentVersion: p.Version, LockedVersion: e.Version}
		switch {
		case !ok:
			st.Status = "new"
			add(rules.ProvNew, p, fmt.Sprintf("New provider %s %s", p.Address, p.Version), "provider:"+p.Address)
		case e.Version != p.Version:
			st.Status = "upgraded"
			add(rules.ProvUpgraded, p, fmt.Sprintf("Provider %s upgraded %s → %s", p.Address, e.Version, p.Version), "provider:"+p.Address+"@"+p.Version)
		case hashesConflict(e.Hashes, p.Hashes):
			st.Status = "mutated"
			add(rules.ProvMutated, p, fmt.Sprintf("Provider %s %s has different checksums than when it was locked: the same version now points at a different binary", p.Address, p.Version), "provider:"+p.Address+"@"+p.Version)
		default:
			st.Status = "ok"
		}
		res.Providers = append(res.Providers, st)
	}
	for _, e := range f.Providers {
		if !current[e.Address] {
			res.Providers = append(res.Providers, ProviderStatus{Address: e.Address, Status: "removed", LockedVersion: e.Version})
		}
	}
	sort.Slice(res.Providers, func(i, j int) bool { return res.Providers[i].Address < res.Providers[j].Address })
}

// hashesConflict reports whether two checksum sets for the same provider
// version cannot describe the same release. The registry's zh: hashes for a
// version never change, so differing zh: sets are a conflict; otherwise any
// shared hash means the same release (init adds h1: hashes per platform).
func hashesConflict(old, cur []string) bool {
	pick := func(hs []string, prefix string) map[string]bool {
		m := map[string]bool{}
		for _, h := range hs {
			if strings.HasPrefix(h, prefix) {
				m[h] = true
			}
		}
		return m
	}
	oz, cz := pick(old, "zh:"), pick(cur, "zh:")
	if len(oz) > 0 && len(cz) > 0 {
		if len(oz) != len(cz) {
			return true
		}
		for h := range oz {
			if !cz[h] {
				return true
			}
		}
		return false
	}
	oh, ch := pick(old, "h1:"), pick(cur, "h1:")
	if len(oh) == 0 || len(ch) == 0 {
		return false
	}
	for h := range oh {
		if ch[h] {
			return false
		}
	}
	return true
}
